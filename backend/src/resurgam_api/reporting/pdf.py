"""Recovery Evidence PDF rendering. Consumes the same
`RecoveryEvidenceReportOut` the JSON endpoint returns -- one aggregation,
two independent renderers, no shared markup with the React frontend (there
is no server-rendered HTML anywhere else in this app).
"""

import base64
import uuid
from pathlib import Path

from jinja2 import Environment, FileSystemLoader
from weasyprint import HTML

from resurgam_api.models.branding_settings import BrandingSettings
from resurgam_api.schemas.reporting import RecoveryEvidenceReportOut

_TEMPLATES_DIR = Path(__file__).parent / "templates"
_ASSETS_DIR = Path(__file__).parent / "assets"
_env = Environment(loader=FileSystemLoader(_TEMPLATES_DIR), autoescape=True)

# The web GUI's defaults: Petrol & Brass `primary` / `accent` (--primary /
# --accent in frontend/src/styles/tokens.css) -- an unconfigured instance's
# PDF matches the unconfigured web GUI exactly, not some third set of colors.
_DEFAULT_PRIMARY_COLOR = "#005f6b"
_DEFAULT_ACCENT_COLOR = "#b08d57"

# Raised directly by the user: an unconfigured instance's PDF showed no
# logo at all, unlike the web GUI (`PrimaryNavigation.tsx`/`LoginPage.tsx`),
# which always falls back to RESURGAM's own static logo when unbranded --
# this closes that inconsistency. A 420px PNG render of
# `frontend/public/logo-full.svg` (the Petrol & Brass-style lockup), bundled here
# rather than read from the frontend's own public folder so the backend
# stays deployable on its own (distributed deployment, ADR/manifest).
# Read once at import time, not per-request -- a static file never changes
# without a redeploy.
_DEFAULT_LOGO_DATA_URI = "data:image/png;base64," + base64.b64encode(
    (_ASSETS_DIR / "resurgam-logo.png").read_bytes()
).decode("ascii")


def render_recovery_evidence_pdf(
    report: RecoveryEvidenceReportOut, branding: BrandingSettings | None = None, *, report_id: uuid.UUID
) -> bytes:
    """`branding`, when a platform_admin has configured one (`api/v1/branding.py`),
    is baked into the PDF as a base64 data URI -- WeasyPrint's
    `HTML(string=...)` accepts `data:` image sources directly, no
    filesystem write needed. Falls back to RESURGAM's own colors when
    unset, and to RESURGAM's own bundled logo when no custom one is
    configured -- the PDF always shows a logo, matching the web GUI.

    `report_id` must be generated by the caller *before* this call (not
    here, and not derived from the PDF bytes) -- it becomes both the
    `report_history` row's own primary key and text printed on every
    page, which only works because it exists before the bytes it's
    printed into do. See the `@page` footer comment in the template for
    why the SHA-256 checksum itself can never do the same.
    """
    template = _env.get_template("recovery_evidence.html.jinja")
    if branding is not None and branding.logo is not None:
        encoded = base64.b64encode(branding.logo).decode("ascii")
        content_type = branding.logo_content_type or "application/octet-stream"
        logo_data_uri = f"data:{content_type};base64,{encoded}"
    else:
        logo_data_uri = _DEFAULT_LOGO_DATA_URI
    primary_color = (branding.primary_color if branding else None) or _DEFAULT_PRIMARY_COLOR
    accent_color = (branding.accent_color if branding else None) or _DEFAULT_ACCENT_COLOR
    html = template.render(
        report=report,
        logo_data_uri=logo_data_uri,
        primary_color=primary_color,
        accent_color=accent_color,
        report_id=report_id,
        app_name=(branding.app_name if branding else None) or "RESURGAM",
    )
    return HTML(string=html, base_url=str(_TEMPLATES_DIR)).write_pdf()
