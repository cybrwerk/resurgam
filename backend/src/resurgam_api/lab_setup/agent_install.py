"""Guided `resurgam-lab-agent` install over a one-time SSH session.

Steps (each one a line in the job's step log):

1. `privileges` -- root, or `sudo -n` (ssh.open_remote_shell).
2. `preflight` -- it is a PVE node (`qm`, `pvesm`), and its Debian release
   matches the one the shipped .deb was built on (dh-virtualenv links the
   build host's Python -- a trixie package fails on bookworm at runtime,
   ADR 0020).
3. `upload` -- the .deb shipped with this backend (`lab_setup/artifacts`),
   into a fresh `mktemp -d` directory, SHA-256 checked on the node.
4. `install` -- `apt-get install -y ./<deb>` (keeps an existing, edited
   /etc/default/resurgam-lab-agent: `--force-confold`).
5. `configure` -- writes /etc/default/resurgam-lab-agent (mode 600) with
   the backend URL, a freshly generated agent token and the overlay
   storage id/dir -- exactly the variables `lab_agent/config.py` reads. The
   node's PBS token is taken from the request, else kept from the existing
   file. Only after the file is in place is the new token's hash committed
   (so a failed run never invalidates a working agent).
6. `service` -- `systemctl enable` + `restart`, then `is-active`.

The temporary directory is removed in every case.
"""

import re
import shlex
from collections.abc import Callable
from dataclasses import dataclass, field

from resurgam_api.lab_setup.artifacts import LabArtifact
from resurgam_api.lab_setup.jobs import JobLog, StepFailed
from resurgam_api.lab_setup.ssh import RemoteShell

LAB_AGENT_ENV_FILE_PATH = "/etc/default/resurgam-lab-agent"
LAB_AGENT_SERVICE = "resurgam-lab-agent"
LAB_AGENT_TOKEN_PLACEHOLDER = "<LAB_AGENT_TOKEN>"
PBS_TOKEN_VARIABLE = "RESURGAM_LAB_AGENT_PBS_TOKEN"

# Debian codename -> the PVE major release built on it (for messages only).
PVE_FOR_DEBIAN = {"bookworm": "PVE 8", "trixie": "PVE 9"}


def comment_safe_name(name: str) -> str:
    """A cluster's display name for a `#` comment in a file RESURGAM writes onto a
    node (env file, pairing script): one line of letters, digits, spaces and
    `._-()`, at most 80 characters. A line break would start a new shell line."""
    return re.sub(r"[^\w .()-]", "", name, flags=re.UNICODE)[:80].strip() or "unnamed"


def render_lab_agent_env_file(
    *,
    cluster_name: str,
    backend_url: str | None,
    overlay_storage_id: str,
    overlay_dir: str,
    agent_token: str = LAB_AGENT_TOKEN_PLACEHOLDER,
    pbs_token: str = "",
) -> str:
    """`/etc/default/resurgam-lab-agent`; variable names per restore-worker
    `lab_agent/config.py`."""
    lines = [
        f"# resurgam-lab-agent for PVE cluster '{comment_safe_name(cluster_name)}' -- generated by RESURGAM's Lab Compute setup.",
        "# After editing: systemctl restart resurgam-lab-agent",
        f"RESURGAM_BACKEND_URL={backend_url or '<RECOVERY_LAB_PUBLIC_BACKEND_URL is not set on the backend>'}",
        f"RESURGAM_LAB_AGENT_TOKEN={agent_token}",
        "# This node's own PBS API token '<user>@<realm>!<name>:<secret>' with at least Datastore.Read on the",
        "# datastore(s) your Application Groups are backed up to. Used only locally, never sent to RESURGAM.",
        f"{PBS_TOKEN_VARIABLE}={pbs_token}",
        f"RESURGAM_LAB_AGENT_OVERLAY_STORAGE_ID={overlay_storage_id}",
        f"RESURGAM_LAB_AGENT_OVERLAY_DIR={overlay_dir}",
    ]
    return "\n".join(lines) + "\n"


def existing_pbs_token(env_file: str) -> str | None:
    """The PBS token from an existing env file (last uncommented assignment)."""
    value = None
    for line in env_file.splitlines():
        match = re.match(rf"^\s*{PBS_TOKEN_VARIABLE}=(.*)$", line)
        if match:
            value = match.group(1).strip().strip('"').strip("'")
    return value or None


def parse_os_release(text: str) -> dict[str, str]:
    values = {}
    for line in text.splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip('"')
    return values


@dataclass
class AgentInstallSpec:
    cluster_name: str
    backend_url: str
    overlay_storage_id: str
    overlay_dir: str
    artifact: LabArtifact
    debian_release: str
    pbs_token: str | None = field(default=None, repr=False)


def _check(shell: RemoteShell, command: str, failure_code: str, failure: str, **kw):
    result = shell.run(command, **kw)
    if not result.ok:
        raise StepFailed(failure_code, failure, result.combined())
    return result


def run_agent_install(
    shell: RemoteShell,
    log: JobLog,
    spec: AgentInstallSpec,
    *,
    issue_token: Callable[[], str],
    commit_token: Callable[[str], None],
) -> None:
    step = log.start(
        "privileges",
        "Logged in as root." if shell.privilege_mode == "root" else "Logged in; using sudo -n for privileged steps.",
    )
    log.finish(step, "ok")
    log.set_result(privilege_mode=shell.privilege_mode)

    step = log.start("preflight", "Checking that this is a PVE node with a matching Debian release.")
    tools = shell.run("command -v qm && command -v pvesm", privileged=False, timeout=30)
    if not tools.ok:
        raise StepFailed(
            "not_a_pve_node",
            "qm/pvesm were not found: this host does not look like a Proxmox VE node. Pick the lab node itself.",
            tools.combined(),
        )
    os_release = parse_os_release(shell.run("cat /etc/os-release", privileged=False, timeout=30).stdout)
    codename = os_release.get("VERSION_CODENAME", "")
    if spec.debian_release and codename != spec.debian_release:
        raise StepFailed(
            "debian_release_mismatch",
            f"The node runs Debian '{codename or 'unknown'}' ({PVE_FOR_DEBIAN.get(codename, 'unknown PVE')}), but "
            f"the shipped resurgam-lab-agent is built for Debian '{spec.debian_release}' "
            f"({PVE_FOR_DEBIAN.get(spec.debian_release, '?')}); its bundled Python environment would fail to start "
            "there. Upgrade the node, or build the package on a matching Debian host (manual mode).",
        )
    installed = shell.run(
        "dpkg-query -W -f='${Version}' resurgam-lab-agent 2>/dev/null || true", privileged=False, timeout=30
    ).stdout.strip()
    log.set_result(previous_version=installed or None)
    log.finish(
        step,
        "ok",
        f"PVE node on Debian {codename}"
        + (f"; resurgam-lab-agent {installed} is installed and will be upgraded." if installed else "."),
    )

    workdir = None
    try:
        step = log.start("upload", f"Uploading {spec.artifact.filename} ({spec.artifact.size // 1024} KiB).")
        # World-traversable so apt's unprivileged `_apt` user can read the
        # .deb; the env file inside is uploaded with mode 600 regardless.
        made = shell.run(
            'd=$(mktemp -d /tmp/resurgam-lab-agent.XXXXXX) && chmod 755 "$d" && echo "$d"', privileged=False, timeout=30
        )
        workdir = made.stdout.strip()
        if not made.ok or not workdir.startswith("/tmp/resurgam-lab-agent."):
            raise StepFailed("command_failed", "Could not create a temporary directory on the node.", made.combined())
        remote_deb = f"{workdir}/{spec.artifact.filename}"
        shell.session.put_file(str(spec.artifact.path), remote_deb, mode=0o644)
        digest = shell.run(f"sha256sum {shlex.quote(remote_deb)}", privileged=False, timeout=60)
        if not digest.ok or digest.stdout.split()[:1] != [spec.artifact.sha256]:
            raise StepFailed(
                "upload_corrupted",
                "The uploaded package's SHA-256 does not match the shipped one; nothing was installed. Try again.",
                digest.combined(),
            )
        log.finish(
            step, "ok", f"Uploaded and verified {spec.artifact.filename} (SHA-256 {spec.artifact.sha256[:12]}…)."
        )

        step = log.start("install", f"Installing resurgam-lab-agent {spec.artifact.version} with apt-get.")
        install = shell.run(
            "DEBIAN_FRONTEND=noninteractive apt-get install -y -o Dpkg::Options::=--force-confdef "
            f"-o Dpkg::Options::=--force-confold {shlex.quote(remote_deb)}",
            timeout=900,
        )
        if not install.ok:
            raise StepFailed(
                "install_failed",
                "apt-get could not install the package (output below). Its dependencies (proxmox-backup-client, "
                "qemu-server, qemu-utils) come from the node's own PVE repositories.",
                install.combined(),
            )
        log.finish(step, "ok", f"resurgam-lab-agent {spec.artifact.version} installed.", install.combined()[-2000:])
        log.set_result(installed_version=spec.artifact.version)

        step = log.start("configure", f"Writing {LAB_AGENT_ENV_FILE_PATH}.")
        pbs_token = spec.pbs_token
        pbs_status = "provided"
        if not pbs_token:
            current = shell.run(f"cat {LAB_AGENT_ENV_FILE_PATH} 2>/dev/null || true", timeout=30).stdout
            pbs_token = existing_pbs_token(current)
            log.add_secret(pbs_token)
            pbs_status = "kept" if pbs_token else "missing"
        agent_token = issue_token()
        log.add_secret(agent_token)
        content = render_lab_agent_env_file(
            cluster_name=spec.cluster_name,
            backend_url=spec.backend_url,
            overlay_storage_id=spec.overlay_storage_id,
            overlay_dir=spec.overlay_dir,
            agent_token=agent_token,
            pbs_token=pbs_token or "",
        )
        staged = f"{workdir}/resurgam-lab-agent.env"
        # Uploaded with mode 600 into the private mktemp directory -- the
        # token never appears on a command line or in any output.
        shell.session.put_bytes(content.encode("utf-8"), staged, mode=0o600)
        _check(
            shell,
            f"install -m 0600 -o root -g root {shlex.quote(staged)} {LAB_AGENT_ENV_FILE_PATH}",
            "command_failed",
            f"Could not write {LAB_AGENT_ENV_FILE_PATH}.",
            timeout=30,
        )
        commit_token(agent_token)
        log.set_result(pbs_token_status=pbs_status)
        if pbs_status == "missing":
            log.finish(
                step,
                "warning",
                f"{LAB_AGENT_ENV_FILE_PATH} written with a new agent token, but without a PBS token: the agent "
                f"refuses to start until {PBS_TOKEN_VARIABLE} is set there (then: systemctl restart "
                "resurgam-lab-agent). Enter it in the form and run the install again, or set it on the node.",
            )
        else:
            log.finish(
                step,
                "ok",
                f"{LAB_AGENT_ENV_FILE_PATH} written with a new agent token"
                + (
                    " and the PBS token you entered."
                    if pbs_status == "provided"
                    else "; the node's PBS token was kept."
                ),
            )

        step = log.start("service", "Enabling and restarting resurgam-lab-agent.")
        _check(
            shell,
            f"systemctl enable {LAB_AGENT_SERVICE} && systemctl restart {LAB_AGENT_SERVICE}",
            "service_failed",
            "systemctl could not enable/restart resurgam-lab-agent.",
            timeout=120,
        )
        active = shell.run(f"sleep 3; systemctl is-active {LAB_AGENT_SERVICE}", timeout=60)
        if active.stdout.strip() != "active":
            journal = shell.run(f"journalctl -u {LAB_AGENT_SERVICE} -n 30 --no-pager", timeout=60)
            log.set_result(service_active=False)
            log.finish(
                step,
                "warning",
                "The service is not running yet (see its log below). "
                + (f"Most likely the missing {PBS_TOKEN_VARIABLE}." if pbs_status == "missing" else ""),
                journal.combined(),
            )
        else:
            log.set_result(service_active=True)
            log.finish(step, "ok", "resurgam-lab-agent is running; waiting for it to check in.")
    finally:
        if workdir and workdir.startswith("/tmp/resurgam-lab-agent."):
            shell.run(f"rm -rf {shlex.quote(workdir)}", privileged=False, timeout=60)
