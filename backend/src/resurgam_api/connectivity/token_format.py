"""Parsing and assembling PBS/PVE API token strings.

RESURGAM stores each token as ONE combined secret, exactly as the vendor's
`Authorization` header expects it after the scheme name:
- PBS: `user@realm!tokenname:secret`  (`PBSAPIToken=...`, pbs docs "API Tokens")
- PVE: `user@realm!tokenname=secret`  (`PVEAPIToken=...`, pve-docs chapter-pveum "API Tokens")

Only the separator differs. Using the wrong one makes every call fail with
HTTP 401, which is why legacy combined input is normalised here. The stored
format is unchanged (other code -- filerestore, the restore-worker -- splits
the stored PBS string on ':').

Formats (vendor API schemas, apidoc.js): user id `name@realm`, token name
PBS `[A-Za-z0-9_][A-Za-z0-9._-]*`, PVE `[A-Za-z][A-Za-z0-9._-]+`. Secrets
generated by both products are UUIDs (e.g. `d63e505a-e3ec-449a-9bc7-
1da610d4ccde`); only "non-empty, no whitespace" is enforced so a valid but
unusual secret is never rejected.
"""

import re
from typing import Literal

Product = Literal["pbs", "pve"]

SEPARATOR: dict[str, str] = {"pbs": ":", "pve": "="}

_USER_ID = r"[^\s:/@!=]+@[A-Za-z0-9_][A-Za-z0-9._\-]*"
_TOKEN_NAME = r"[A-Za-z0-9_][A-Za-z0-9._\-]*"
USER_ID_RE = re.compile(rf"^{_USER_ID}$")
TOKEN_ID_RE = re.compile(rf"^(?P<user>{_USER_ID})!(?P<name>{_TOKEN_NAME})$")
TOKEN_NAME_RE = re.compile(rf"^{_TOKEN_NAME}$")
_COMBINED_RE = re.compile(rf"^(?P<token_id>{_USER_ID}!{_TOKEN_NAME})[:=](?P<secret>\S+)$")

EXAMPLE_TOKEN_ID = {"pbs": "resurgam@pbs!resurgam", "pve": "resurgam@pve!resurgam"}
EXAMPLE_USER_ID = {"pbs": "root@pam", "pve": "root@pam"}


def token_id_error(token_id: str, product: Product) -> str | None:
    """None if `token_id` is valid, else an explanation naming the expected
    format and an example (never echoes a secret -- a token ID isn't one)."""
    value = token_id.strip()
    if TOKEN_ID_RE.match(value):
        return None
    hint = f"Expected format user@realm!tokenname, e.g. '{EXAMPLE_TOKEN_ID[product]}'."
    if "!" not in value:
        return f"The token ID must contain '!' between the user and the token name. {hint}"
    if ":" in value or "=" in value:
        return (
            "The token ID must not contain the secret -- enter only user@realm!tokenname here and the secret "
            f"in the separate secret field. {hint}"
        )
    if "@" not in value.split("!", 1)[0]:
        return f"The user part of the token ID needs a realm (user@realm, e.g. root@pam). {hint}"
    return f"The token ID is not valid. {hint}"


def token_secret_error(token_secret: str) -> str | None:
    value = token_secret.strip()
    if not value:
        return "The token secret must not be empty. It is shown once when the token is created (a UUID)."
    if any(ch.isspace() for ch in value):
        return "The token secret must not contain spaces. Paste only the secret value (a UUID)."
    if "!" in value and "@" in value:
        return (
            "This looks like a full token (user@realm!name...). Enter the token ID and only the secret value "
            "(the UUID) in their own fields."
        )
    return None


def assemble(token_id: str, token_secret: str, product: Product) -> str:
    """Combine ID and secret with the product's separator."""
    return f"{token_id.strip()}{SEPARATOR[product]}{token_secret.strip()}"


def normalize_combined(api_token: str, product: Product) -> str:
    """Legacy combined input: fix a wrong separator (`:` for PVE / `=` for
    PBS -- the exact mistake behind "HTTP 401 on everything"). A value that
    doesn't look like `user@realm!name<sep>secret` at all is kept verbatim
    (backward compatibility for the deprecated field)."""
    value = api_token.strip()
    match = _COMBINED_RE.match(value)
    if match is None:
        return value
    return assemble(match.group("token_id"), match.group("secret"), product)


def token_id_from_stored(stored: str | None) -> str | None:
    """The non-secret token ID part of a stored combined token, or None if
    it can't be parsed. Never returns any part of the secret.

    A stored value that is *only* a token ID (no separator, no secret) is
    what a configuration import (`config_backup`) stores for a PBS/PVE
    connection whose secret was deliberately left out of the export -- its
    ID is returned as-is, so the edit form can keep it and the admin only
    has to enter the secret (see `token_secret_missing`)."""
    if not stored:
        return None
    value = stored.strip()
    match = _COMBINED_RE.match(value)
    if match:
        return match.group("token_id")
    return value if TOKEN_ID_RE.match(value) else None


def token_secret_missing(stored: str | None) -> bool:
    """True when a stored token has no secret part at all: empty/absent, or
    a bare `user@realm!tokenname` placeholder written by a configuration
    import. Such a connection can't authenticate -- callers report it as
    `auth_failed` ("secret not set") without contacting the server."""
    if stored is None or not stored.strip():
        return True
    return bool(TOKEN_ID_RE.match(stored.strip()))
